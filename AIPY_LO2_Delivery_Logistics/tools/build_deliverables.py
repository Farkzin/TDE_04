def latest_run() -> Path:
    name = (PROJECT / "outputs" / "LATEST_SUCCESSFUL_RUN.txt").read_text(encoding="utf-8").splitlines()[0].strip()
    return PROJECT / "outputs" / "runs" / name


def build_html() -> str:
    body = markdown.markdown(REPORT_MD.read_text(encoding="utf-8"), extensions=["tables", "fenced_code"])
    body = body.replace("<h2>", '<h2 class="first">', 1)
    run = latest_run()
    appendix = ['<h2>Appendix A – ST4 report generated by the run</h2>',
                f"<pre>{html.escape((run / 'st4_batch_report.txt').read_text(encoding='utf-8'))}</pre>",
                '<h2>Appendix B – ST5 report generated by the run</h2>',
                f"<pre>{html.escape((run / 'st5_weather_report.txt').read_text(encoding='utf-8'))}</pre>",
                '<h2>Appendix C – Run history and logs</h2>',
                f"<pre>{html.escape((PROJECT / 'outputs' / 'run_history.csv').read_text(encoding='utf-8'))}</pre>"]
    for log in sorted((PROJECT / "logs").glob("*.log")):
        appendix.append(f"<h3>{log.name}</h3><pre>{html.escape(log.read_text(encoding='utf-8'))}</pre>")
    appendix.append('<h2>Appendix D – Saved API response and metadata (data/external/open_meteo)</h2>')
    for js in sorted((PROJECT / "data" / "external" / "open_meteo").glob("*.json")):
        appendix.append(f"<h3>{js.name}</h3><pre>{html.escape(js.read_text(encoding='utf-8'))}</pre>")
    appendix.append('<h2>Appendix E – Run manifest</h2>'
                    f"<pre>{html.escape((run / 'run_manifest.json').read_text(encoding='utf-8'))}</pre>")
    cover = f"""<div class="cover">
<div class="sub">AI-ASSISTED PYTHON FOR BUSINESS PROBLEM SOLVING</div>
<h1>Evaluation Project – LO 2</h1>
<div class="sub">Study Themes 4 and 5</div>
<div class="sub">Project Topic: Delivery and Logistics Management</div>
<div class="sub">Professor: Evandro Zatti · Semester: 2026/2</div>
<div class="team"><b>Team Members</b><br>{'<br>'.join(TEAM)}</div>
<div class="sub" style="margin-top:40px">Weekly delivery batch automation (ST4) and weather API integration (ST5)</div>
</div>"""
    return (f"<!DOCTYPE html><html><head><meta charset='utf-8'><title>AIPY LO2</title><style>{CSS}</style>"
            f"</head><body>{cover}{body}{''.join(appendix)}</body></html>")


def build_pdf() -> Path:
    OUT.mkdir(exist_ok=True)
    html_file = OUT / "_report.html"
    html_file.write_text(build_html(), encoding="utf-8")
    pdf = OUT / PDF_NAME
    subprocess.run([str(EDGE), "--headless", "--disable-gpu", "--no-pdf-header-footer",
                    f"--print-to-pdf={pdf}", html_file.as_uri()], check=True, timeout=120)
    html_file.unlink()
    return pdf


def build_zip() -> Path:
    OUT.mkdir(exist_ok=True)
    target = OUT / ZIP_NAME
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(PROJECT.rglob("*")):
            rel = path.relative_to(PROJECT)
            if path.is_dir() or any(part in EXCLUDE_DIRS for part in rel.parts) or path.suffix == ".pyc":
                continue
            zf.write(path, Path(PROJECT.name) / rel)
    return target


if __name__ == "__main__":
    print(build_pdf())
    print(build_zip())
